const cp850Table: Record<number, string> = {};
for (const [byte, unicode] of CP850_MAP) cp850Table[byte] = String.fromCodePoint(unicode);
for (let i = 0; i < 0x80; i++) cp850Table[i] = String.fromCodePoint(i);

export function decodeCP850(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  let out = '';
  for (let i = 0; i < bytes.length; i++) out += cp850Table[bytes[i]] || '�';
  return out;
}
